// Creates only disposable users and cleans them up. Never modifies existing accounts.
import assert from 'node:assert/strict';
import { randomUUID, randomBytes } from 'node:crypto';
import { createClient } from '@supabase/supabase-js';

if (process.env.RUN_BACKEND_VERIFICATION !== 'yes') throw new Error('Set RUN_BACKEND_VERIFICATION=yes to create and remove disposable verification accounts.');
const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const options = { auth: { autoRefreshToken: false, persistSession: false } };
const admin = createClient(url, process.env.SUPABASE_SERVICE_ROLE_KEY, options);
const created = [];
const files = [];
const passed = [];
const check = (result) => { if (result.error) throw result.error; return result.data; };
async function user() {
  const email = `applyiq-verification-${randomUUID()}@example.invalid`;
  const password = randomBytes(32).toString('base64url');
  const { user } = check(await admin.auth.admin.createUser({ email, password, email_confirm: true }));
  created.push(user.id);
  const client = createClient(url, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY, options);
  check(await client.auth.signInWithPassword({ email, password }));
  return { id: user.id, client };
}

try {
  const a = await user(); const b = await user();
  assert.equal(check(await a.client.from('profiles').select('id').single()).id, a.id);
  passed.push('Signup profile trigger works with restricted function permissions');
  const apps = Array.from({ length: 5 }, () => ({ id: randomUUID(), user_id: a.id, company: 'Synthetic verification', role: 'Test role', url: '' }));
  check(await a.client.from('applications').insert(apps));
  assert.ok((await a.client.from('applications').insert({ ...apps[0], id: randomUUID() })).error);
  check(await a.client.from('applications').upsert({ ...apps[0], notes: 'Idempotent retry' }).select('id').single());
  assert.equal(check(await a.client.from('applications').select('id')).length, 5);
  passed.push('Free application limit and idempotent save retries');
  assert.equal(check(await b.client.from('applications').select('id').eq('user_id', a.id)).length, 0);
  assert.ok((await b.client.from('applications').update({ notes: 'Must not save' }).eq('id', apps[0].id).select('id').single()).error);
  passed.push('Cross-account reads and writes denied');
  check(await admin.from('subscriptions').upsert({ user_id: a.id, status: 'active' }));
  const resumes = Array.from({ length: 3 }, (_, i) => ({ id: randomUUID(), user_id: a.id, name: `Synthetic ${i}`, text: `Synthetic resume ${i}`, is_default: false }));
  check(await a.client.from('resumes').insert(resumes));
  assert.ok((await a.client.from('resumes').insert({ ...resumes[0], id: randomUUID() })).error);
  check(await a.client.rpc('set_default_resume', { resume_id: resumes[0].id }));
  check(await a.client.rpc('set_default_resume', { resume_id: resumes[1].id }));
  assert.ok((await b.client.rpc('set_default_resume', { resume_id: resumes[1].id })).error);
  assert.equal(check(await a.client.from('resumes').select('id').eq('is_default', true)).length, 1);
  assert.equal(check(await a.client.from('profiles').select('resume_text').single()).resume_text, resumes[1].text);
  passed.push('Pro resume limit and atomic owned default selection');
  check(await admin.from('subscriptions').update({ status: 'canceled' }).eq('user_id', a.id));
  const reservations = await Promise.all(Array.from({ length: 4 }, () => admin.rpc('reserve_ai_analysis', { account_id: a.id, feature_name: 'ai_analysis' })));
  assert.equal(reservations.filter(r => !r.error).length, 3);
  assert.equal(reservations.filter(r => r.error).length, 1);
  assert.ok((await a.client.rpc('reserve_ai_analysis', { account_id: b.id, feature_name: 'ai_analysis' })).error);
  check(await admin.from('subscriptions').update({ status: 'active' }).eq('user_id', a.id));
  check(await admin.rpc('reserve_ai_analysis', { account_id: a.id, feature_name: 'ai_analysis' }));
  passed.push('Concurrent Free AI quota, server-only reservations, and Pro entitlement');
  const checkouts = await Promise.all(Array.from({ length: 2 }, () => admin.rpc('begin_billing_checkout', { account_id: a.id, selected_plan: 'monthly' })));
  assert.equal(check(checkouts[0])[0].request_id, check(checkouts[1])[0].request_id);
  assert.ok((await admin.rpc('begin_billing_checkout', { account_id: a.id, selected_plan: 'annual' })).error);
  assert.ok((await a.client.rpc('begin_billing_checkout', { account_id: a.id, selected_plan: 'monthly' })).error);
  passed.push('Checkout coordination and client permission boundaries');
  const path = `${a.id}/${randomUUID()}-synthetic.txt`;
  check(await a.client.storage.from('resumes').upload(path, new TextEncoder().encode('Synthetic verification only'), { contentType: 'text/plain' }));
  files.push(path);
  assert.ok((await b.client.storage.from('resumes').download(path)).error);
  assert.equal(check(await admin.storage.getBucket('resumes')).file_size_limit, 10485760);
  passed.push('Private storage ownership and file size limit');
  const jobId = apps[0].id;
  check(await a.client.from('applications').update({ description: 'Synthetic saved posting', captured_at: new Date().toISOString(), next_action: 'Synthetic follow-up', next_action_due: '2026-11-10' }).eq('id', jobId));
  const version = { record_id: randomUUID(), job_id: jobId, material_kind: 'resume', material_title: 'Submitted résumé snapshot', material_body: { name: 'Synthetic résumé', text: resumes[0].text, filePath: null, sourceResumeId: resumes[0].id } };
  check(await a.client.rpc('save_application_material', version));
  check(await a.client.rpc('save_application_material', version));
  check(await a.client.from('resumes').update({ text: 'Changed vault text' }).eq('id', resumes[0].id));
  assert.equal(check(await a.client.from('application_materials').select('body').eq('id', version.record_id).single()).body.text, resumes[0].text);
  assert.ok((await a.client.rpc('save_application_material', { ...version, material_body: { ...version.material_body, text: 'Overwritten' } })).error);
  assert.ok((await a.client.from('application_materials').update({ title: 'Overwrite' }).eq('id', version.record_id)).error);
  assert.ok((await a.client.from('application_materials').delete().eq('id', version.record_id)).error);
  passed.push('Immutable job résumé snapshots survive vault edits and idempotent retries');
  const analysisId = randomUUID(); const letterId = randomUUID();
  const result = { matchScore: 82, company: 'Synthetic verification', role: 'Test role', matchedKeywords: ['Synthetic'], missingKeywords: ['Example'], aiSuggestion: 'Synthetic suggestion', coverLetter: 'Synthetic cover letter', interviewQuestions: [{ q: 'Synthetic question', hint: 'Synthetic hint' }], salaryRange: 'Unknown', industry: 'Synthetic', seniority: 'Unknown', culture: [] };
  const analysis = { job_id: jobId, resume_record: version.record_id, analysis_record: analysisId, letter_record: letterId, resume_snapshot: null, analysis_result: result, posting_text: 'Synthetic saved posting', source_url: '' };
  const outcomes = await Promise.all([a.client.rpc('save_application_analysis', analysis), a.client.rpc('save_application_analysis', analysis)]);
  outcomes.forEach(check);
  assert.equal(check(await a.client.from('application_materials').select('id').eq('application_id', jobId)).length, 3);
  assert.equal(check(await a.client.from('application_materials').select('body').eq('id', analysisId).single()).body.resumeVersionId, version.record_id);
  passed.push('Concurrent analysis retries save one complete, linked analysis and cover-letter bundle');
  const broken = { ...analysis, analysis_record: randomUUID(), letter_record: randomUUID(), analysis_result: { ...result, coverLetter: 'x'.repeat(30001) } };
  assert.ok((await a.client.rpc('save_application_analysis', broken)).error);
  assert.equal(check(await a.client.from('application_materials').select('id').eq('id', broken.analysis_record)).length, 0);
  passed.push('Failed analysis bundle rolls back every version atomically');
  assert.equal(check(await b.client.from('application_materials').select('id').eq('application_id', jobId)).length, 0);
  assert.ok((await b.client.rpc('save_application_material', { ...version, record_id: randomUUID() })).error);
  assert.ok((await b.client.from('application_materials').insert({ id: randomUUID(), user_id: b.id, application_id: jobId, kind: 'resume', title: 'Foreign parent', body: version.material_body })).error);
  assert.ok((await a.client.rpc('save_application_analysis', { ...analysis, job_id: apps[1].id, analysis_record: randomUUID(), letter_record: randomUUID() })).error);
  passed.push('Cross-account and cross-application material references are denied');
  const submission = { record_id: randomUUID(), job_id: jobId, resume_version: version.record_id, cover_version: letterId, submission_date: '2026-11-02' };
  (await Promise.all([a.client.rpc('record_application_submission', submission), a.client.rpc('record_application_submission', submission)])).forEach(check);
  assert.equal(check(await a.client.from('application_submissions').select('id').eq('application_id', jobId)).length, 1);
  assert.ok((await a.client.rpc('record_application_submission', { ...submission, record_id: randomUUID(), resume_version: analysisId })).error);
  assert.ok((await a.client.rpc('record_application_submission', { ...submission, record_id: randomUUID(), job_id: apps[1].id })).error);
  assert.equal(check(await b.client.from('application_submissions').select('id')).length, 0);
  check(await a.client.from('applications').update({ status: 'interview' }).eq('id', jobId));
  const reopened = check(await a.client.from('applications').select('*').eq('id', jobId).single());
  assert.equal(reopened.description, 'Synthetic saved posting'); assert.equal(reopened.next_action, 'Synthetic follow-up');
  assert.equal(reopened.next_action_due, '2026-11-10'); assert.equal(reopened.applied_at, '2026-11-02');
  assert.equal(reopened.selected_resume_id, version.record_id);
  const timeline = check(await a.client.from('application_status_events').select('status').eq('application_id', jobId).order('created_at'));
  assert.deepEqual(timeline.map(row => row.status), ['saved', 'applied', 'interview']);
  passed.push('Submission history, next action, posting text, and actual status timeline survive reopening');
  check(await a.client.from('applications').delete().eq('id', jobId));
  for (const table of ['application_materials', 'application_submissions', 'application_status_events']) assert.equal(check(await a.client.from(table).select('id').eq('application_id', jobId)).length, 0);
  passed.push('Deleting a disposable application cascades its workspace without dangling references');
  console.log(JSON.stringify({ passed: passed.length, checks: passed }, null, 2));
} finally {
  if (files.length) check(await admin.storage.from('resumes').remove(files));
  for (const id of created) check(await admin.auth.admin.deleteUser(id));
  console.log('Disposable verification accounts and files removed.');
}
